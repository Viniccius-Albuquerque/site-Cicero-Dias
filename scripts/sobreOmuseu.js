// CARREGAR TÓPICO
function loadTopic(topicId) {
    if (!topicsData[topicId]) return;
    
    const topic = topicsData[topicId];
    const contentBody = document.getElementById('contentBody');
    
    // Injeta o conteúdo na tela
    contentBody.innerHTML = topic.content;

    if (topicId === 'ciceroDias') {
        initSlider();
    }
    
    // CORREÇÃO: Aplica a cor escura na tela inteira se for o tópico de baronatos
    const footer = document.querySelector('.museum-footer');

    if (topicId === 'baronatos') {

        contentBody.style.backgroundColor = '#151617';
        contentBody.style.color = '#ede7e1';

        footer.style.backgroundColor = '#151617';
        footer.style.color = '#ede7e1';

    } else {

        contentBody.style.backgroundColor = '#fff8f0';
        contentBody.style.color = '#333333';

        footer.style.backgroundColor = '#fff8f0';
        footer.style.color = '#333333';
    }

    footer.classList.toggle('dark-footer', topicId === 'baronatos');
    
    // SELEÇÃO DO CONTAINER DE SCROLL
    const container = document.querySelector('.content-scroll');
    if (container) {
        container.scrollTop = 0; // Faz o texto voltar para o início (topo)
    }
}

// MARCAR BOTÃO ATIVO
function setActiveNavItem(selectedButton) {
    document.querySelectorAll('.nav-item').forEach(btn => {
        btn.classList.remove('active');
    });
    selectedButton.classList.add('active');
}

// ABRIR E FECHAR SUBTÓPICOS
document.querySelectorAll('.nav-item').forEach(button => {
    button.addEventListener('click', () => {
        const topicAttr = button.getAttribute('data-topic');
        const subtopics = button.parentElement.querySelector('.subtopics');
        
        // Verifica se este item já está aberto (tem a classe 'open')
        const isAlreadyOpen = subtopics ? subtopics.classList.contains('open') : false;

        // 1. SEMPRE carrega o conteúdo ao clicar (mesmo que já esteja aberto)
        loadTopic(topicAttr);
        setActiveNavItem(button);

        // 2. Fecha TODOS os outros subtopicos primeiro
        document.querySelectorAll('.subtopics').forEach(sub => {
            sub.classList.remove('open');
        });

        if (subtopics && !isAlreadyOpen) {
            subtopics.classList.add('open');
            
            // Pequeno ajuste para a sidebar rolar e mostrar o que abriu
            setTimeout(() => {
                button.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
            }, 200);
        }
    });
});

